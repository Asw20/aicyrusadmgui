import time, re, os
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH', '/usr/bin/chromium'),args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1000})
 page.set_default_timeout(10000)
 errors=[]
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8000')
 page.get_by_label('Workspace name').fill('Acme Infrastructure')
 page.get_by_label('Work email').fill('browser-'+str(int(time.time()))+'@example.com')
 page.get_by_label('Password',exact=True).fill('Browser testing 12345')
 page.get_by_role('button',name='Create workspace').click()
 page.get_by_role('heading',name='Workspace overview').wait_for()
 page.locator('.page-heading [data-action="create-user"]').click()
 page.get_by_label('User ID').fill('casey')
 page.get_by_role('button',name='Create user mailbox').click()
 page.get_by_role('dialog').wait_for(state='hidden')
 page.locator('#nav [data-page="users"]').click()
 page.get_by_role('searchbox').fill('casey')
 page.get_by_role('button',name='Manage casey').click()
 page.get_by_role('button',name='Rename',exact=True).click()
 page.get_by_label('New mailbox name').fill('user.casey2')
 page.get_by_role('button',name='Save changes').click()
 page.get_by_role('dialog').wait_for(state='hidden')
 page.locator('#nav [data-page="mailboxes"]').click()
 page.get_by_role('searchbox').fill('casey2')
 page.get_by_role('button',name='Permissions',exact=True).click()
 page.get_by_label('Principal',exact=True).fill('support-team')
 page.get_by_label('Permission preset').select_option('lr')
 page.get_by_role('button',name='Save permissions').click()
 page.get_by_text('support-team',exact=True).wait_for()
 page.screenshot(path='/tmp/cyrus-acl.png',full_page=True)
 page.get_by_role('button',name='Close dialog').click()
 page.locator('#nav [data-page="activity"]').click()
 page.get_by_role('cell',name=re.compile('set acl')).wait_for()
 page.locator('#nav [data-page="settings"]').click()
 page.get_by_role('heading',name='Server settings',exact=True).wait_for()
 page.set_viewport_size({'width':390,'height':844})
 page.locator('#nav [data-page="overview"]').click()
 page.screenshot(path='/tmp/cyrus-mobile.png',full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile layout overflows horizontally'
 print('Browser flow passed: register, create, search, rename, ACL, activity, settings, mobile.')
 print('JS errors:',errors)
 assert not errors
 b.close()
